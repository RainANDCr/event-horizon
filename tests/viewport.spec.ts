test('renders with WebGL2 and resizes the drawing buffer', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('console', message => {
    if (message.type() === 'error') errors.push(message.text())
  })
  await page.goto('/')
  await expect(page.locator('canvas')).toHaveAttribute('data-rendered', 'true')
  const screenshot = await page.locator('canvas').screenshot({ style: 'header, footer { visibility: hidden }' })
  const pixels = await page.evaluate(async (png) => {
    const image = new Image()
    image.src = 'data:image/png;base64,' + png
    await image.decode()
    const canvas = new OffscreenCanvas(image.width, image.height)
    const context = canvas.getContext('2d')!
    context.drawImage(image, 0, 0)
    const y = Math.floor(image.height / 2)
    const sample = (x: number) => Array.from(context.getImageData(x, y, 1, 1).data).slice(0, 3)
    return { center: sample(Math.floor(image.width / 2)), sky: sample(Math.floor(image.width / 4)) }
  }, screenshot.toString('base64'))
  expect(pixels.center).toEqual([0, 0, 0])
  expect(Math.max(...pixels.sky)).toBeGreaterThan(15)
  await page.screenshot({ path: 'test-results/stage-8.png' })
  await page.setViewportSize({ width: 420, height: 820 })
  await expect(page.locator('canvas')).toHaveAttribute('width', '420')
  await expect(page.locator('canvas')).toHaveAttribute('height', '820')
  expect(errors).toEqual([])
})

