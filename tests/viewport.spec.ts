test('downloads real PNG and WebM data and releases the capture track', async ({ page }) => {
  await page.setViewportSize({ width: 780, height: 530 })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.addInitScript(() => {
    const NativeRecorder = window.MediaRecorder
    window.MediaRecorder = class extends NativeRecorder {
      override start(timeslice?: number) {
        this.addEventListener('dataavailable', event => {
          if (event.data.size) document.documentElement.dataset.webmData = 'ready'
        })
        super.start(timeslice)
      }
    }
    const capture = HTMLCanvasElement.prototype.captureStream
    HTMLCanvasElement.prototype.captureStream = function (rate) {
      const stream = capture.call(this, rate)
      for (const track of stream.getTracks()) {
        const stop = track.stop.bind(track)
        track.stop = () => {
          stop()
          document.documentElement.dataset.track = track.readyState
        }
      }
      return stream
    }
  })
  await page.goto('/')
  await expect(page.locator('canvas')).toHaveAttribute('data-rendered', 'true')
  await page.getByRole('button', { name: '设置', exact: true }).click()
  await page.getByRole('checkbox', { name: '截图水印' }).check()
  await page.getByRole('button', { name: '关闭设置' }).click()
  const pngDownload = page.waitForEvent('download')
  await page.getByRole('button', { name: '截图' }).click()
  const png = await readFile(await (await pngDownload).path())
  expect(png.subarray(0, 8).toString('hex')).toBe('89504e470d0a1a0a')
  const pixel = await page.evaluate(async (data) => {
    const image = new Image()
    image.src = 'data:image/png;base64,' + data
    await image.decode()
    const context = new OffscreenCanvas(image.width, image.height).getContext('2d')!
    context.drawImage(image, 0, 0)
    return Math.max(...Array.from(context.getImageData(0, 0, image.width, 32).data).filter((_, index) => index % 4 !== 3))
  }, png.toString('base64'))
  expect(pixel).toBeGreaterThan(15)
  await page.getByRole('button', { name: '录制 WebM' }).click()
  await expect(page.getByRole('status')).toContainText('正在录制')
  await expect(page.locator('html')).toHaveAttribute('data-webm-data', 'ready', { timeout: 15000 })
  const videoDownload = page.waitForEvent('download')
  await page.getByRole('button', { name: '结束录制' }).click()
  const webm = await readFile(await (await videoDownload).path())
  expect(webm.subarray(0, 4).toString('hex')).toBe('1a45dfa3')
  const dimensions = await page.evaluate(async (data) => {
    const video = document.createElement('video')
    await new Promise<void>((resolve, reject) => {
      video.onloadeddata = () => resolve()
      video.onerror = () => reject(new Error('WebM decode failed'))
      video.src = 'data:video/webm;base64,' + data
    })
    return [video.videoWidth, video.videoHeight]
  }, webm.toString('base64'))
  expect(dimensions).toEqual([780, 530])
  await expect(page.locator('html')).toHaveAttribute('data-track', 'ended')
})

